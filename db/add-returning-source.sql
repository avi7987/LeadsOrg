-- =====================================================================
--  add-returning-source.sql — הוספת מקור "לקוחה חוזרת" ללידים
--
--  למה צריך: עמודת ה-source בטבלת leads מוגבלת לרשימת ערכים מותרת.
--  כדי שאפשר יהיה לבחור "לקוחה חוזרת" בהוספת ליד ידני, מוסיפים אותה לרשימה.
--
--  איך מריצים (פעם אחת):
--    Supabase → SQL Editor → מדביקים ומריצים (Run).
-- =====================================================================

alter table leads drop constraint if exists leads_source_check;

alter table leads add constraint leads_source_check
  check (source in ('פרסום','הודעת פופ-אפ','ידני','אורגני','המלצה','לקוחה חוזרת'));
