--  update-popup-copy.sql — ניסוח חדש, אישי וחם לשיחת הפופ-אפ
--
--  מה השתנה:
--   • שאלה 2 מאגדת "מתי" + "איפה" למשפט אחד טבעי → מקבלים גם מיקום,
--     בלי להוסיף עוד הודעה ללקוחה. היא גם מזמינה לספר על האירוע,
--     כך שברוב המקרים נדע שמדובר בכלה כבר בשלב הזה.
--   • ניסוח נפרד ומרגש לכלות — נכנס לפעולה ברגע שהמערכת מזהה.
--     אם התגלה רק בסוף — לפחות הודעת הסיום (הזכורה ביותר) תהיה מותאמת.
--   • הסיום מבטיח חזרה אישית — מוריד חרדה ובונה אמון.
--
--  אפשר לערוך הכל גם מהדשבורד: הגדרות ← שיחת הפופ-אפ.
--  איך מריצים (פעם אחת): Supabase → SQL Editor → הדבקה → Run.
-- =====================================================================

-- ── הניסוח הרגיל (לכל אירוע) ──
update settings set value = to_jsonb(array[
  'היי! 💕 כאן איה — כל כך כיף שפנית אליי!
איך קוראים לך?',

  'נעים מאוד {{name}} 🌸
ספרי לי קצת על האירוע — מתי הוא, ואיפה הוא מתקיים?',

  'איזה כיף {{name}} ✨
ומה חשוב לך שאדאג לו — איפור, תסרוקת, או שתיהם?'
]) where key = 'popup_questions';

update settings set value = to_jsonb(
  'תודה {{name}} יקרה 💕
רשמתי הכל, ואני חוזרת אלייך אישית עוד היום עם כל הפרטים ✨
מחכה לשמוע עוד על האירוע שלך!'::text
) where key = 'popup_thanks';

-- ── ניסוח מיוחד לכלות 👑 (ריק = ישתמש בניסוח הרגיל) ──
insert into settings(key, value) values
  ('popup_questions_bride', to_jsonb(array[
    'מזל טוב!! 💍✨ כאן איה — ואיזה כיף שפנית אליי!
איך קוראים לך?',

    'נעים מאוד {{name}} 🥂
ספרי לי — מתי החתונה, ואיפה היא מתקיימת?',

    'מתרגשת בשבילך {{name}} 💍
ומה חשוב לך שאדאג לו ביום הגדול — איפור, תסרוקת, או שתיהם?'
  ])),
  ('popup_thanks_bride', to_jsonb(
    'תודה {{name}} יקרה 💕
רשמתי הכל, ואני חוזרת אלייך אישית עוד היום.
להיות חלק מהיום הכי חשוב שלך — זו זכות בשבילי 💍✨'::text
  ))
on conflict (key) do nothing;
