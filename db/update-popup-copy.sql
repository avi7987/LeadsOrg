-- =====================================================================
--  update-popup-copy.sql — ניסוח חדש, אישי וחם לשיחת הפופ-אפ
--
--  מה השתנה:
--   • שאלה 2 מאגדת "מתי" + "איפה" למשפט אחד טבעי → מקבלים גם מיקום,
--     בלי להוסיף עוד הודעה ללקוחה.
--   • הניסוח מדבר על האירוע (מרגש), לא על "סוג השירות" (טכני).
--   • הסיום מבטיח חזרה אישית — מוריד חרדה ובונה אמון.
--
--  אפשר לערוך הכל גם מהדשבורד: הגדרות ← שיחת הפופ-אפ.
--  איך מריצים (פעם אחת): Supabase → SQL Editor → הדבקה → Run.
-- =====================================================================

update settings set value = to_jsonb(array[
  'היי! 💕 כאן איה — כל כך כיף שפנית אליי!
איך קוראים לך?',

  'נעים מאוד {{name}} 🌸
ספרי לי — מתי האירוע, ואיפה הוא מתקיים?',

  'איזה כיף {{name}} ✨
ומה חשוב לך שאדאג לו — איפור, תסרוקת, או שתיהם?'
]) where key = 'popup_questions';

update settings set value = to_jsonb(
  'תודה {{name}} יקרה 💕
רשמתי הכל, ואני חוזרת אלייך אישית עוד היום עם כל הפרטים ✨
מחכה לשמוע עוד על האירוע שלך!'::text
) where key = 'popup_thanks';
